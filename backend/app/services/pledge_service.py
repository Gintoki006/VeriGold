"""
VeriGold — Pledge Service (Phase 4 §4.4.1)

Implements the pledge lifecycle:
  register_pledge — submits RegisterPledge to Fabric, inserts PledgeMirror + Transaction
  close_pledge    — verifies ownership, submits ClosePledge, updates mirror + Transaction

Design:
  - pledge_id is generated by the backend (PLG-{12 random hex uppercase}) before the
    Fabric call so we have it before any network round-trip.
  - Off-chain PledgeMirror is updated after confirmed Fabric tx so the SQL mirror
    always trails the on-chain state; it is never ahead.
  - Both operations are wrapped in DB transactions that roll back if anything fails
    after the Fabric submit (tx hash stored as pending first, updated to confirmed).
"""
import logging
from datetime import datetime, timezone
from uuid import uuid4

from sqlalchemy import select
from sqlalchemy.ext.asyncio import AsyncSession

from app.models.pledge_mirror import PledgeMirror, PledgeStatus
from app.models.transaction import Transaction, TransactionStatus, TransactionType
from app.services.fabric_gateway import FabricGatewayClient
from app.utils.errors import PledgeNotFoundError, UnauthorizedPledgeError

logger = logging.getLogger(__name__)


def _generate_pledge_id() -> str:
    return f"PLG-{uuid4().hex[:12].upper()}"


async def register_pledge(
    borrower_hash: str,
    gold_fingerprint: str,
    amount_range: int,
    lender_id: int,
    lender_msp_id: str,
    fabric: FabricGatewayClient,
    db: AsyncSession,
) -> dict:
    """
    Register a new pledge on Fabric and persist the off-chain mirror.

    Returns:
        {"pledge_id": str, "transaction_hash": str}
    """
    pledge_id = _generate_pledge_id()

    # Insert pending Transaction record before the Fabric call
    tx_record = Transaction(
        lender_id=lender_id,
        pledge_id=pledge_id,
        transaction_hash=None,                  # unknown until Fabric responds
        transaction_type=TransactionType.REGISTER_PLEDGE,
        status=TransactionStatus.pending,
    )
    db.add(tx_record)
    await db.flush()

    # Submit to Fabric
    tx_hash = await fabric.submit_transaction(
        "RegisterPledge",
        [pledge_id, borrower_hash, gold_fingerprint, str(amount_range)],
        lender_msp_id=lender_msp_id,
    )

    # Persist off-chain mirror
    mirror = PledgeMirror(
        pledge_id=pledge_id,
        borrower_hash=borrower_hash,
        gold_fingerprint=gold_fingerprint,
        lender_id=lender_id,
        amount_range=amount_range,
        status=PledgeStatus.active,
        transaction_hash=tx_hash,
    )
    db.add(mirror)

    # Update transaction record to confirmed
    tx_record.transaction_hash = tx_hash
    tx_record.status = TransactionStatus.confirmed
    await db.commit()

    logger.info("Pledge registered: %s tx=%s", pledge_id, tx_hash)
    return {"pledge_id": pledge_id, "transaction_hash": tx_hash}


async def close_pledge(
    pledge_id: str,
    lender_id: int,
    lender_msp_id: str,
    fabric: FabricGatewayClient,
    db: AsyncSession,
) -> dict:
    """
    Close an existing pledge.

    Raises:
        PledgeNotFoundError   — pledge_id does not exist in mirror table
        UnauthorizedPledgeError — pledge belongs to a different lender
    Returns:
        {"pledge_id": str, "status": "CLOSED", "transaction_hash": str}
    """
    # Verify ownership against off-chain mirror before hitting Fabric
    stmt = select(PledgeMirror).where(PledgeMirror.pledge_id == pledge_id)
    result = await db.execute(stmt)
    mirror: PledgeMirror | None = result.scalar_one_or_none()

    if mirror is None:
        raise PledgeNotFoundError(pledge_id)

    if mirror.lender_id != lender_id:
        raise UnauthorizedPledgeError(pledge_id)

    if mirror.status == PledgeStatus.closed:
        return {
            "pledge_id": pledge_id,
            "status": "CLOSED",
            "transaction_hash": mirror.transaction_hash,
            "message": "Pledge was already closed.",
        }

    # Insert pending Transaction before Fabric call
    tx_record = Transaction(
        lender_id=lender_id,
        pledge_id=pledge_id,
        transaction_hash=None,
        transaction_type=TransactionType.CLOSE_PLEDGE,
        status=TransactionStatus.pending,
    )
    db.add(tx_record)
    await db.flush()

    # Submit to Fabric
    tx_hash = await fabric.submit_transaction(
        "ClosePledge",
        [pledge_id],
        lender_msp_id=lender_msp_id,
    )

    # Update mirror
    mirror.status = PledgeStatus.closed
    mirror.closed_at = datetime.now(timezone.utc)
    mirror.transaction_hash = tx_hash

    # Update transaction record
    tx_record.transaction_hash = tx_hash
    tx_record.status = TransactionStatus.confirmed
    await db.commit()

    logger.info("Pledge closed: %s tx=%s", pledge_id, tx_hash)
    return {"pledge_id": pledge_id, "status": "CLOSED", "transaction_hash": tx_hash}
