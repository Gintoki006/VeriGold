"""VeriGold — PledgeMirror model (read-replica of on-chain pledge for fast queries)."""
from datetime import datetime
import enum
from sqlalchemy import DateTime, Enum, ForeignKey, Integer, String, func
from sqlalchemy.orm import Mapped, mapped_column, relationship

from .base import Base


class PledgeStatus(str, enum.Enum):
    active = "active"
    closed = "closed"
    flagged = "flagged"


class PledgeMirror(Base):
    """
    Off-chain read-replica of Fabric pledge state for fast SQL queries.
    Source of truth is always the Fabric ledger — this is a cache only.
    Updated by the backend after every successful Fabric transaction.
    """
    __tablename__ = "pledge_mirrors"

    id: Mapped[int] = mapped_column(primary_key=True, autoincrement=True)
    pledge_id: Mapped[str] = mapped_column(
        String(64), unique=True, nullable=False, index=True,
        comment="UUID generated by backend before submitting to Fabric"
    )
    borrower_hash: Mapped[str] = mapped_column(
        String(64), nullable=False, index=True,
        comment="HMAC-SHA256 of Aadhaar — never stores plaintext"
    )
    gold_fingerprint: Mapped[str] = mapped_column(
        String(64), nullable=False,
        comment="SHA-256 of canonical gold JSON"
    )
    lender_id: Mapped[int] = mapped_column(
        ForeignKey("lenders.id", ondelete="RESTRICT"), nullable=False, index=True
    )
    amount_range: Mapped[int] = mapped_column(
        Integer, nullable=False,
        comment="Bucket code 0-4 per PRD §11.2"
    )
    status: Mapped[PledgeStatus] = mapped_column(
        Enum(PledgeStatus), nullable=False, default=PledgeStatus.active
    )
    transaction_hash: Mapped[str | None] = mapped_column(
        String(128), nullable=True,
        comment="Fabric transaction ID that created/last-updated this pledge"
    )
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), nullable=False
    )
    closed_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True), nullable=True
    )

    lender = relationship("Lender", lazy="selectin")
