"""
VeriGold — Risk Factor Icon Mapping and Schema Validation Tests

Validates that rule explanations generated by the risk engine map cleanly
into recognized UI factor keys with a default fallback to prevent crashes.
"""
import pytest

KNOWN_FACTOR_ICONS = {
    "active_pledges": "📋",
    "exposure": "💰",
    "velocity": "⚡",
    "gold_match": "🥇",
    "risk signal": "⚡",
    "default": "📊",
}


def test_factor_icon_resolution():
    """Verify that recognized factors resolve their icon and unknown factors use fallback."""
    def resolve_icon(factor_name: str | None) -> str:
        if not factor_name:
            return KNOWN_FACTOR_ICONS["default"]
        key = factor_name.lower().strip()
        return KNOWN_FACTOR_ICONS.get(key, KNOWN_FACTOR_ICONS["default"])

    assert resolve_icon("active_pledges") == "📋"
    assert resolve_icon("velocity") == "⚡"
    assert resolve_icon("gold_match") == "🥇"
    assert resolve_icon("exposure") == "💰"
    assert resolve_icon("risk signal") == "⚡"
    assert resolve_icon("unknown_future_factor") == "📊"
    assert resolve_icon(None) == "📊"
